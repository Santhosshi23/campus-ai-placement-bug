// In local dev, Vite proxies "/api" to the backend (see vite.config.ts).
// For production deployments where frontend & backend are hosted separately
// (e.g. Vercel + Render), set VITE_API_BASE_URL to the backend's public URL.
const configuredBase = import.meta.env.VITE_API_BASE_URL as string | undefined;
const BASE = configuredBase ? `${configuredBase.replace(/\/$/, "")}/api` : "/api";

export class ApiError extends Error {
  status: number;
  constructor(message: string, status: number) {
    super(message);
    this.status = status;
  }
}

async function request<T>(path: string, options: RequestInit = {}): Promise<T> {
  const res = await fetch(`${BASE}${path}`, {
    ...options,
    headers: {
      "Content-Type": "application/json",
      ...(options.headers || {}),
    },
  });
  if (!res.ok) {
    let detail = `Request failed (${res.status})`;
    try {
      const body = await res.json();
      detail = body.detail || detail;
    } catch {
      /* ignore */
    }
    throw new ApiError(detail, res.status);
  }
  return res.json() as Promise<T>;
}

export const api = {
  get: <T>(path: string) => request<T>(path, { method: "GET" }),
  post: <T>(path: string, body?: unknown) =>
    request<T>(path, { method: "POST", body: body ? JSON.stringify(body) : undefined }),
};
